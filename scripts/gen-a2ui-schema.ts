/**
 * Writes resources/gui-bridge/modes/a2ui-schema.json: A2UI v1.0's message schema (`agent_to_renderer.json`), its
 * `common_types.json` and OMPdesk's catalog (`a2ui-catalog.json`) merged into one root, every cross-file `$ref`
 * rewritten to the root's `#/$defs/…`. Stock's JSON-Schema validator (pi-ai `validateJsonSchemaValue`) resolves only
 * local refs, and inlining (`dereferenceJsonSchema`) would cut A2UI's recursive DynamicValue/FunctionCall refs to `{}`.
 *
 * The A2UI files come from the pinned `@a2ui/web_core` package (Apache-2.0, Google LLC); a test regenerates the file
 * from it and fails on drift (src/main/bridge-a2ui.test.ts).
 *
 *   bun scripts/gen-a2ui-schema.ts [<schemas dir>]   default: node_modules/@a2ui/web_core/src/v1_0/schemas
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

export const A2UI_SCHEMA_PACKAGE_DIR = "node_modules/@a2ui/web_core/src/v1_0/schemas";
const ROOT = resolve(import.meta.dirname, "..");
const CATALOG_FILE = join(ROOT, "resources/gui-bridge/modes/a2ui-catalog.json");
const OUT_FILE = join(ROOT, "resources/gui-bridge/modes/a2ui-schema.json");

function isObject(value: Json | undefined): value is JsonObject {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** A copy of `value` with every `$ref` string passed through `rewrite`. */
function rewriteRefs(value: Json, rewrite: (ref: string) => string): Json {
	if (Array.isArray(value)) return value.map(item => rewriteRefs(item, rewrite));
	if (!isObject(value)) return value;
	const out: JsonObject = {};
	for (const [key, item] of Object.entries(value)) {
		out[key] = key === "$ref" && typeof item === "string" ? rewrite(item) : rewriteRefs(item, rewrite);
	}
	return out;
}

/** The `$defs` keys the catalog's parts get in the merged root. */
export const catalogDef = {
	component: (name: string) => `catalog_component_${name}`,
	function: (name: string) => `catalog_function_${name}`,
	def: (name: string) => `catalog_${name}`,
} as const;

function envelopeRef(ref: string): string {
	const common = /^common_types\.json#\/\$defs\/(\w+)$/.exec(ref);
	if (common) return `#/$defs/${common[1]}`;
	const catalog = /^catalog\.json#\/\$defs\/(\w+)$/.exec(ref);
	if (catalog) return `#/$defs/${catalogDef.def(catalog[1])}`;
	if (/^#\/\$defs\/\w+$/.test(ref)) return ref;
	throw new Error(`gen-a2ui-schema: unexpected $ref ${ref} in an A2UI schema`);
}

function catalogRef(ref: string): string {
	const common = /^common_types\.json#\/\$defs\/(\w+)$/.exec(ref);
	if (common) return `#/$defs/${common[1]}`;
	const local = /^#\/(components|functions|\$defs)\/(\w+)$/.exec(ref);
	if (!local) throw new Error(`gen-a2ui-schema: unexpected $ref ${ref} in the catalog`);
	const [, part, name] = local;
	if (part === "components") return `#/$defs/${catalogDef.component(name)}`;
	if (part === "functions") return `#/$defs/${catalogDef.function(name)}`;
	return `#/$defs/${catalogDef.def(name)}`;
}

/** Merges the three schemas into one root whose refs are all local. Throws on a ref form or a name clash it does not know. */
export function mergeA2uiSchema(agentToRenderer: Json, commonTypes: Json, catalog: Json): JsonObject {
	if (!isObject(agentToRenderer) || !isObject(commonTypes) || !isObject(catalog)) {
		throw new Error("gen-a2ui-schema: every input must be a JSON object");
	}
	const defs: JsonObject = {};
	const put = (key: string, schema: Json) => {
		if (key in defs) throw new Error(`gen-a2ui-schema: two definitions named ${key}`);
		defs[key] = schema;
	};
	const { $defs: envelopeDefs, $id: _envelopeId, ...envelope } = agentToRenderer;
	for (const [name, schema] of Object.entries(isObject(envelopeDefs) ? envelopeDefs : {})) {
		put(name, rewriteRefs(schema, envelopeRef));
	}
	const commonDefs = commonTypes.$defs;
	for (const [name, schema] of Object.entries(isObject(commonDefs) ? commonDefs : {})) {
		put(name, rewriteRefs(schema, envelopeRef));
	}
	for (const [part, key] of [
		["components", catalogDef.component],
		["functions", catalogDef.function],
		["$defs", catalogDef.def],
	] as const) {
		const entries = catalog[part];
		for (const [name, schema] of Object.entries(isObject(entries) ? entries : {})) {
			put(key(name), rewriteRefs(schema, catalogRef));
		}
	}
	return {
		$comment:
			"Generated by scripts/gen-a2ui-schema.ts from @a2ui/web_core's v1.0 agent_to_renderer.json and common_types.json (Copyright 2025 Google LLC, Apache-2.0) and resources/gui-bridge/modes/a2ui-catalog.json. Do not edit.",
		...(rewriteRefs(envelope, envelopeRef) as JsonObject),
		$defs: defs,
	};
}

function readJson(file: string): Json {
	return JSON.parse(readFileSync(file, "utf8")) as Json;
}

/** The merged schema built from the A2UI schemas in `dir` and OMPdesk's catalog. */
export function buildA2uiSchema(dir: string): JsonObject {
	return mergeA2uiSchema(
		readJson(join(dir, "agent_to_renderer.json")),
		readJson(join(dir, "common_types.json")),
		readJson(CATALOG_FILE),
	);
}

export function a2uiSchemaText(schema: JsonObject): string {
	return `${JSON.stringify(schema, null, "\t")}\n`;
}

if (import.meta.main) {
	const dir = resolve(process.argv[2] ?? join(ROOT, A2UI_SCHEMA_PACKAGE_DIR));
	writeFileSync(OUT_FILE, a2uiSchemaText(buildA2uiSchema(dir)));
	console.log(`gen-a2ui-schema: wrote ${OUT_FILE}`);
}
