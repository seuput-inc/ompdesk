/**
 * Registry of every point where OMPdesk touches stock omp: what OMPdesk code reaches it, which stock side it
 * relies on, and which tests guard it. One entry per point; ids are stable (L launch, Q stdio RPC, B bridge,
 * H stock-helper and stock processes, U settings UI, F stock file formats, C copies of stock logic).
 *
 * `touchpoints.test.ts` keeps this file true to the code: every runtime `@oh-my-pi/*` reference in production code
 * comes from a listed file and names a specifier listed in the same entry's `stock`, every module
 * `capabilities.ts` requires is listed, and every `*-stock` test guards an entry. Add a new omp touchpoint here
 * in the same change that adds it to the code.
 */

/** A test that runs against the installed stock omp: every one guards some touchpoint (`tests`). */
export const STOCK_TEST_FILE = /-stock\.(?:test|e2e)\.[cm]?[jt]sx?$/;

export type TouchpointArea = "launch" | "rpc" | "bridge" | "helper" | "settings" | "files" | "copy";

/** `public`: documented omp behaviour (omp://rpc.md, extensions.md, sdk.md, settings.md, session.md). `internal`: anything else. */
export type TouchpointContract = "public" | "internal";

/**
 * `public-api`: an omp public API (TouchpointContract `public`) does the same, so the copy goes. `registered`: it
 * stays, for the reason given, and its tests pin it to stock. `open`: it stays, and nothing pins it to stock yet.
 */
export interface CopyDisposition {
	kind: "public-api" | "registered" | "open";
	reason: string;
}

export interface Touchpoint {
	/** L01.. launch, Q rpc, B bridge, H helper, U settings, F files, C copies. */
	id: string;
	area: TouchpointArea;
	contract: TouchpointContract;
	/** One line, English. In-memory patches of omp objects say so. */
	summary: string;
	/** Repo paths (no globs) of the OMPdesk code that touches it. */
	files: readonly string[];
	/** The omp side: module specifiers (a package root is its package name), CLI and RPC names, file formats, doc references. */
	stock: readonly string[];
	/** Repo paths of the tests that guard it. */
	tests: readonly string[];
	/** Commits that had to follow an omp change, with what changed in omp. */
	changes?: readonly string[];
	/** Copies only (area `copy`): what becomes of it. */
	disposition?: CopyDisposition;
}

